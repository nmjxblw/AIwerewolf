def format_config_summary(args: Any) -> list[str]:
    lines: list[str] = []
    for key in CONFIG_SUMMARY_KEYS:
        value = getattr(args, key)
        if isinstance(value, bool):
            value = t("summary.yes") if value else t("summary.no")
        lines.append(f"{t('label.' + key)}: {value}")
    return lines
