_current_lang = "zh-CN"


def set_language(lang: str) -> None:
    global _current_lang
    _current_lang = lang if lang in {"zh-CN", "en-US"} else "zh-CN"


def _table() -> dict[str, str]:
    return {**STRINGS, **EN_STRINGS} if _current_lang == "en-US" else STRINGS


def t(key: str, *args: Any, **kwargs: Any) -> str:
    value = _table().get(key, key)
    return value.format(*args, **kwargs) if args or kwargs else value


def t_en(key: str, *args: Any, **kwargs: Any) -> str:
    value = EN_STRINGS.get(key, STRINGS.get(key, key))
    return value.format(*args, **kwargs) if args or kwargs else value


